export function assistantSuggestions(step: number): string[] {
  return suggestions[step] ?? suggestions[0];
}

export function assistantGreeting(step: number): string {
  return greetings[step] ?? greetings[0];
}

export function assistantReply(question: string, step: number): string {
  const hit = replies.find(reply => reply.keys.some(key => question.includes(key)));
  if (hit) return hit.text;
  return step === 0
    ? "我先記下這個問題。你也可以切到「共備討論」，和其他老師一起討論。"
    : "這個問題我先記在這堂課的共備紀錄裡。你也可以切到「共備討論」，和其他老師一起討論。";
}
